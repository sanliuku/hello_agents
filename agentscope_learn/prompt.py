# -*- coding: utf-8 -*-
"""三国狼人杀中文提示词（AgentScope v2）

v2 中输出格式由 reply(..., structured_schema=...) 统一约束，
系统提示词只负责描述玩家身份、阵营目标和行为准则。
"""


class ChinesePrompts:
    """中文提示词管理类"""

    # 各角色的身份与行动准则
    ROLE_GUIDANCE = {
        "狼人": """- 你属于狼人阵营，目标是消灭所有好人或使狼人数量不小于好人
- 夜晚可以与其他狼人协商并投票选择击杀目标
- 白天要隐藏狼人身份，通过发言误导好人
- 知道其他狼队友是谁，可以与他们配合""",
        "预言家": """- 你属于好人阵营，目标是找出并帮助淘汰所有狼人
- 每晚可以秘密查验一名玩家是狼人还是好人
- 应选择合适的时机公布查验结果，引导好人投票
- 注意过早暴露身份可能被狼人击杀""",
        "女巫": """- 你属于好人阵营，拥有解药和毒药各一瓶，全场各只能使用一次
- 解药可以救活当晚被狼人击杀的玩家
- 毒药可以在夜晚毒杀任意一名玩家
- 请谨慎判断局势，在关键时刻使用道具""",
        "猎人": """- 你属于好人阵营，被投票出局（或被狼人击杀）时可以开枪带走一名玩家
- 请在关键时刻使用技能，尽量带走狼人
- 被女巫毒杀时无法发动技能""",
        "村民": """- 你属于好人阵营，没有特殊技能
- 只能通过听取发言、逻辑推理和投票找出狼人
- 请仔细观察其他玩家发言中的破绽""",
    }

    @classmethod
    def get_role_prompt(cls, role: str, character: str) -> str:
        """获取角色系统提示词：身份 + 性格 + 阵营准则"""
        guidance = cls.ROLE_GUIDANCE.get(role, cls.ROLE_GUIDANCE["村民"])

        return f"""你是{character}，正在参与一场三国主题狼人杀游戏，你在游戏中扮演{role}。

你的性格特点：{cls._get_character_trait(character)}

行动准则：
{guidance}

请始终以{character}的口吻进行发言和推理，与其他玩家博弈。"""

    @staticmethod
    def _get_character_trait(character: str) -> str:
        """三国人物性格（与 roles.py 保持一致）"""
        traits = {
            "刘备": "仁德宽厚，善于团结众人，说话温和有礼",
            "关羽": "忠义刚烈，言辞直接，重情重义",
            "张飞": "性格豪爽，说话大声直接，容易冲动",
            "诸葛亮": "智慧超群，分析透彻，言辞谨慎",
            "赵云": "忠勇双全，话语简洁有力",
            "曹操": "雄才大略，善于权谋，话语犀利",
            "司马懿": "深谋远虑，城府极深，言辞含蓄",
            "周瑜": "才华横溢，略显傲气，分析精准",
            "孙权": "年轻有为，善于决断，话语果决",
        }
        return traits.get(character, "性格温和，说话得体")
